export function detectLanguageCode(text: string) {
  const normalized = text.trim();
  if (Array.from(normalized).length < 5) return undefined;

  if (normalized.length >= 20) {
    const detected = youtubeCodes[franc(normalized, { minLength: 20 })];
    if (detected) return detected;
  }

  return scriptCodes.find(([script]) => script.test(normalized))?.[1];
}